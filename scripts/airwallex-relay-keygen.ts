/**
 * Generates the Ed25519 relay key for the live sandbox runner.
 * - private key -> local .env RAILGUARD_RELAY_PRIVATE_KEY (base64 PEM, never printed, git-ignored)
 * - public key  -> packages/kernel/src/adapters/airwallex/relayPublicKey.ts (committed)
 * Refuses to rotate an existing key unless --rotate is passed.
 *
 *   bun scripts/airwallex-relay-keygen.ts
 */
import { createPrivateKey, createPublicKey, generateKeyPairSync } from "node:crypto"
import { writeFileSync } from "node:fs"
import { join } from "node:path"
import { relayKeyId } from "../packages/kernel/src/adapters/airwallex/relay"
import { setEnvVar } from "./lib-env-file"

const root = join(import.meta.dir, "..")
const envPath = join(root, ".env")
const rotate = process.argv.includes("--rotate")
let privatePem: string
const existing = process.env.RAILGUARD_RELAY_PRIVATE_KEY?.trim()
if (existing && !rotate) {
  privatePem = Buffer.from(existing, "base64").toString("utf8")
} else {
  const { privateKey } = generateKeyPairSync("ed25519")
  privatePem = privateKey.export({ type: "pkcs8", format: "pem" }).toString()
  setEnvVar(envPath, "RAILGUARD_RELAY_PRIVATE_KEY", Buffer.from(privatePem).toString("base64"))
}
const publicPem = createPublicKey(createPrivateKey(privatePem)).export({ type: "spki", format: "pem" }).toString()
writeFileSync(
  join(root, "packages/kernel/src/adapters/airwallex/relayPublicKey.ts"),
  `/** Public half of the live-runner relay key (safe to commit). Generated by scripts/airwallex-relay-keygen.ts. */\nexport const RAILGUARD_RELAY_PUBLIC_KEY_PEM = ${JSON.stringify(publicPem)}\n`,
)
console.log(JSON.stringify({ ok: true, keyId: relayKeyId(publicPem), rotated: !existing || rotate }))
